'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  appVersion: () => ipcRenderer.invoke('app:version'),
  isElectron: true,
  pickFiles: () => ipcRenderer.invoke('dialog:files'),
  pickFolder: () => ipcRenderer.invoke('dialog:folder'),
  scan: (files, dirs) => ipcRenderer.invoke('lib:scan', { files, dirs }),
  cancelScan: () => ipcRenderer.invoke('scan:cancel'),
  onScanProgress: (cb) => ipcRenderer.on('scan:progress', (_e, p) => cb(p)),
  trackDetail: (p) => ipcRenderer.invoke('track:detail', p),
  upCheck: (key) => ipcRenderer.invoke('up:check', key),
  trackLyric: (p) => ipcRenderer.invoke('track:lyric', p),
  trackCover: (p) => ipcRenderer.invoke('track:cover', p),
  mediaUrl: (p) => ipcRenderer.invoke('media:url', p),
  /* 网易云：全部返回 { ok, ... } / { ok:false, error:{code,message} } */
  neSearch: (q, limit) => ipcRenderer.invoke('ne:search', { q, limit }),
  neSongs: (ids) => ipcRenderer.invoke('ne:songs', ids),
  nePlaylist: (id) => ipcRenderer.invoke('ne:playlist', id),
  neAlbum: (id) => ipcRenderer.invoke('ne:album', id),
  neLink: (v) => ipcRenderer.invoke('ne:link', v),
  neCover: (url, size) => ipcRenderer.invoke('ne:cover', url, size),
  neUrl: (id, quality) => ipcRenderer.invoke('ne:url', id, quality),
  /* 账号：扫码登录（二维码 SVG + 状态轮询），凭证不回传渲染层 */
  neStatus: () => ipcRenderer.invoke('ne:status'),
  neQr: () => ipcRenderer.invoke('ne:qr'),
  neQrPoll: () => ipcRenderer.invoke('ne:qrPoll'),
  neLogout: () => ipcRenderer.invoke('ne:logout'),
  /* 账号歌单：我的歌单 + 推荐歌单 + 每日推荐 + 私人FM */
  neHome: () => ipcRenderer.invoke('ne:home'),
  neDaily: () => ipcRenderer.invoke('ne:daily'),
  neFm: (n) => ipcRenderer.invoke('ne:fm', n),
  /* 哔哩哔哩：搜索 / 详情 / 取流预检 / 封面 / 登录（扫码或 Cookie） */
  bilSearch: (q, limit) => ipcRenderer.invoke('bil:search', { q, limit }),
  bilView: (bvid) => ipcRenderer.invoke('bil:view', bvid),
  bilUrl: (bvid, cid) => ipcRenderer.invoke('bil:url', bvid, cid),
  bilFavs: () => ipcRenderer.invoke('bil:favs'),
  bilFavList: (mediaId, page) => ipcRenderer.invoke('bil:favList', mediaId, page),
  bilCover: (url, size) => ipcRenderer.invoke('bil:cover', url, size),
  bilStatus: () => ipcRenderer.invoke('bil:status'),
  bilQr: () => ipcRenderer.invoke('bil:qr'),
  bilQrCancel: () => ipcRenderer.invoke('bil:qrCancel'),
  bilQrPoll: () => ipcRenderer.invoke('bil:qrPoll'),
  bilLogin: (cookie) => ipcRenderer.invoke('bil:login', cookie),
  bilLogout: () => ipcRenderer.invoke('bil:logout'),
  /* QQ 音乐 / 酷狗音乐：扫码登录与多账号（凭据只留在主进程，不回传渲染层） */
  accBegin: (provider) => ipcRenderer.invoke('acc:begin', { provider }),
  accPoll: (provider) => ipcRenderer.invoke('acc:poll', { provider }),
  accRefresh: (provider) => ipcRenderer.invoke('acc:refresh', { provider }),
  accCancel: (provider) => ipcRenderer.invoke('acc:cancel', { provider }),
  accStatus: (provider) => ipcRenderer.invoke('acc:status', { provider }),
  accList: (provider) => ipcRenderer.invoke('acc:list', provider ? { provider } : {}),
  accCurrent: (provider) => ipcRenderer.invoke('acc:current', { provider }),
  accSwitch: (id) => ipcRenderer.invoke('acc:switch', { id }),
  accLogout: (id, provider) => ipcRenderer.invoke('acc:logout', id ? { id } : { provider }),
  accAudio: (req) => ipcRenderer.invoke('acc:audio', req),
  accInvalidate: (provider) => ipcRenderer.invoke('acc:invalidate', provider ? { provider } : {}),
  accMeta: (key, albumMid) => ipcRenderer.invoke('acc:meta', key, albumMid || ''),
  accVip: () => ipcRenderer.invoke('acc:vip'),
  accPlaylists: (provider) => ipcRenderer.invoke('acc:playlists', { provider }),
  accRecommend: (provider) => ipcRenderer.invoke('acc:recommend', { provider }),
  accTracks: (provider, id, dirId) => ipcRenderer.invoke('acc:tracks', { provider, id, dirId }),
  accSearch: (provider, keyword, page) => ipcRenderer.invoke('acc:search', { provider, keyword, page }),
  idnGet: () => ipcRenderer.invoke('idn:get'),
  idnSet: (provider, accountId) => ipcRenderer.invoke('idn:set', { provider, accountId }),
  onIdnChanged: (cb) => ipcRenderer.on('idn:changed', (_e, p) => cb(p)),
  onAccEvent: (cb) => ipcRenderer.on('acc:event', (_e, p) => cb(p)),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  setSettingsSync: (s) => ipcRenderer.send('settings:set-sync', s),
  getLibrary: () => ipcRenderer.invoke('library:get'),
  setLibrary: (l) => ipcRenderer.invoke('library:set', l),
  setLibrarySync: (l) => ipcRenderer.send('library:set-sync', l),
  winMin: () => ipcRenderer.invoke('win:min'),
  winMax: () => ipcRenderer.invoke('win:max'),
  winClose: () => ipcRenderer.invoke('win:close'),
  winFullscreen: (on) => ipcRenderer.invoke('win:fullscreen', on),
  isFullscreen: () => ipcRenderer.invoke('win:fullscreen:get'),
  registerKeys: (list) => ipcRenderer.invoke('keys:register', list),
  clearKeys: () => ipcRenderer.invoke('keys:clear'),
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  onGlobalKey: (cb) => ipcRenderer.on('key:global', (_e, id) => cb(id)),
  onWinState: (cb) => ipcRenderer.on('win:state', (_e, s) => cb(s))
});
